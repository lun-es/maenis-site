MARWIL.aPartir = m => { const v = Object.values(m.prix).flatMap(x => x == null ? [] : typeof x === "object" ? Object.values(x) : [x]).filter(x => x > 0); return v.length ? Math.min(...v) : null; };
// les prix tenus par Marie dans l'onglet « Prix » du carnet remplacent ceux de ce fichier (gardés 10 minutes)
MARWIL.chargerPrix = function () {
  if (!MARWIL.api) return Promise.resolve();
  const poser = d => MARWIL.modeles.forEach(m => { if (d[m.id] && Object.keys(d[m.id]).length) m.prix = d[m.id]; });
  try { const c = JSON.parse(sessionStorage.getItem("mm-prix") || "null"); if (c && Date.now() - c.t < 600000) { poser(c.d); return Promise.resolve(); } } catch (e) {}
  const delai = new Promise(ok => setTimeout(ok, 4000));
  const lire = fetch(MARWIL.api + "?prix=1").then(r => r.json()).then(r => { if (r.ok) { poser(r.prix); try { sessionStorage.setItem("mm-prix", JSON.stringify({ t: Date.now(), d: r.prix })); } catch (e) {} } }).catch(() => {});
  return Promise.race([lire, delai]);
};
